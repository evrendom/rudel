import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createBrowserSession } from "./driver.mjs";

const sourceUrl =
	"http://127.0.0.1:4175/__lens-atoms/interfere-title?opaline-copy=agent-sessions";
const marketingRoot = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	"..",
);
const vendorRoot = path.join(
	marketingRoot,
	"src/styles/vendor/interfere/hero-title",
);
const generatedRoot = path.join(marketingRoot, "src/components/generated");
const fontRoot = path.join(marketingRoot, "public/fonts");
const artifactRoot = path.resolve(
	marketingRoot,
	"../../.context/extractions/hero-title",
);

const session = await createBrowserSession({
	url: sourceUrl,
	width: 1280,
	height: 800,
	dpr: 1,
});
let capture;
try {
	await session.waitFor(
		'document.documentElement.hasAttribute("data-interfere-title-ready")',
	);
	capture = await session.evaluate(`(() => {
		const title = document.querySelector("[data-interfere-title-source]");
		const stylesheet = [...document.styleSheets].find((sheet) => sheet.href?.includes("/globals-"));
		const isolation = document.querySelector("style[data-interfere-title-isolation]");
		const font = document.querySelector('link[rel="preload"][as="font"]');
		if (!title || !stylesheet?.href || !isolation || !font?.href) {
			throw new Error("The settled hero title source is incomplete");
		}
		return {
			titleHtml: title.outerHTML,
			bodyClass: document.body.className,
			documentClass: document.documentElement.className,
			stylesheetUrl: stylesheet.href,
			isolationCss: isolation.textContent,
			fontUrl: font.href,
		};
	})()`);
	await session.screenshot(path.join(artifactRoot, "source.png"));
} finally {
	await session.close();
}

const [cssResponse, fontResponse] = await Promise.all([
	fetch(capture.stylesheetUrl),
	fetch(capture.fontUrl),
]);
if (!cssResponse.ok || !fontResponse.ok) {
	throw new Error(
		`Could not download title assets: CSS ${cssResponse.status}, font ${fontResponse.status}`,
	);
}
const [remoteCss, fontBytes] = await Promise.all([
	cssResponse.text(),
	fontResponse.arrayBuffer(),
]);
const localFontName = "interfere-inter-variable.woff2";
const sourceCss = remoteCss.replaceAll(
	capture.fontUrl,
	`/fonts/${localFontName}`,
);

await Promise.all([
	mkdir(vendorRoot, { recursive: true }),
	mkdir(generatedRoot, { recursive: true }),
	mkdir(fontRoot, { recursive: true }),
	mkdir(artifactRoot, { recursive: true }),
]);
await Promise.all([
	writeFile(path.join(vendorRoot, "source.css"), sourceCss),
	writeFile(path.join(vendorRoot, "isolation.css"), capture.isolationCss),
	writeFile(
		path.join(generatedRoot, "hero-title-source-data.ts"),
		`// Generated by tools/extract-hero-title.mjs from the settled source route.\nexport const titleHtml = ${JSON.stringify(capture.titleHtml)};\nexport const bodyClass = ${JSON.stringify(capture.bodyClass)};\nexport const documentClass = ${JSON.stringify(capture.documentClass)};\n`,
	),
	writeFile(path.join(fontRoot, localFontName), Buffer.from(fontBytes)),
	writeFile(path.join(artifactRoot, "title.html"), capture.titleHtml),
	writeFile(
		path.join(artifactRoot, "manifest.json"),
		`${JSON.stringify(
			{
				sourceUrl,
				...capture,
				cssBytes: Buffer.byteLength(sourceCss),
				fontBytes: fontBytes.byteLength,
				fontSha256: createHash("sha256")
					.update(Buffer.from(fontBytes))
					.digest("hex"),
			},
			null,
			2,
		)}\n`,
	),
]);

