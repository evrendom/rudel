import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import selectorParser from "postcss-selector-parser";

const marketingRoot = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	"..",
);
const vendorRoot = path.join(
	marketingRoot,
	"src/styles/vendor/attio/dashboard",
);
const sourceDataPath = path.join(
	marketingRoot,
	"src/components/generated/dashboard-source-data.ts",
);
const naturalizedDataPath = path.join(
	marketingRoot,
	"src/components/generated/dashboard-data.ts",
);
const sourceScriptPath = path.join(
	marketingRoot,
	"src/scripts/dashboard-extracted.ts",
);
const naturalizedScriptPath = path.join(
	marketingRoot,
	"src/scripts/dashboard.ts",
);
const renameMapPath = path.join(
	marketingRoot,
	"tools/rename-map/dashboard.json",
);
const scopeClass = "opaline-dashboard-scope";
const renameMap = JSON.parse(await readFile(renameMapPath, "utf8"));

const replaceTokens = (source, replacements) => {
	let result = source;
	for (const [from, to] of Object.entries(replacements).toSorted(
		([left], [right]) => right.length - left.length,
	)) {
		result = result.replaceAll(from, to);
	}
	return result;
};

const zeroSpecificityScope = () => {
	const scope = selectorParser.pseudo({ value: ":where" });
	scope.append(
		selectorParser.selector({
			nodes: [selectorParser.className({ value: scopeClass })],
		}),
	);
	return scope;
};

const transformSelector = selectorParser((selectors) => {
	selectors.each((selector) => {
		selector.walkClasses((node) => {
			const renamed = renameMap.classes[node.value];
			if (renamed) node.value = renamed;
		});
		selector.walkAttributes((node) => {
			const renamed = renameMap.attributes[node.attribute];
			if (renamed) node.attribute = renamed;
		});
		selector.walkPseudos((node) => {
			if (node.value === ":root" || node.value === ":host") {
				node.replaceWith(selectorParser.className({ value: scopeClass }));
			}
		});
		selector.walkTags((node) => {
			if (node.value === "html" || node.value === "body") {
				node.replaceWith(selectorParser.className({ value: scopeClass }));
			}
		});
		let containsScope = false;
		selector.walkClasses((node) => {
			if (node.value === scopeClass) containsScope = true;
		});
		if (!containsScope) {
			selector.prepend(selectorParser.combinator({ value: " " }));
			selector.prepend(zeroSpecificityScope());
		}
	});
});

const naturalizeCss = (source, from) => {
	const root = postcss.parse(source, { from });
	root.walkRules((rule) => {
		if (
			rule.parent?.type === "atrule" &&
			rule.parent.name.endsWith("keyframes")
		)
			return;
		rule.selector = transformSelector.processSync(rule.selector);
	});
	return root.toString();
};

const readExportedValue = (source, name) => {
	const line = source
		.split("\n")
		.find((candidate) => candidate.startsWith(`export const ${name} = `));
	if (!line) throw new Error(`Could not read dashboard field: ${name}`);
	return JSON.parse(
		line
			.slice(`export const ${name} = `.length)
			.replace(/ as const;$/, "")
			.replace(/;$/, ""),
	);
};

const naturalizeMarkup = (markup) => {
	let result = markup.replace(
		/class="([^"]*)"/g,
		(_, classNames) =>
			`class="${classNames
				.split(/\s+/)
				.map((className) => renameMap.classes[className] ?? className)
				.join(" ")}"`,
	);
	for (const [source, candidate] of Object.entries(
		renameMap.attributes,
	).toSorted(([left], [right]) => right.length - left.length)) {
		result = result.replaceAll(source, candidate);
	}
	return result;
};

const [sourceCss, compositionCss, sourceData, sourceScript] = await Promise.all(
	[
		readFile(path.join(vendorRoot, "source.css"), "utf8"),
		readFile(path.join(vendorRoot, "composition.css"), "utf8"),
		readFile(sourceDataPath, "utf8"),
		readFile(sourceScriptPath, "utf8"),
	],
);
const stringFields = [
	"dashboardHtml",
	"shellHtml",
	"dataPanelHtml",
	"reportingPanelHtml",
	"mobileDataHtml",
	"mobileReportingHtml",
];
const pageRoot = readExportedValue(sourceData, "dashboardPageRoot");
pageRoot.htmlClass = pageRoot.htmlClass
	.split(/\s+/)
	.map((className) => renameMap.classes[className] ?? className)
	.join(" ");

const naturalizedData = [
	"// Generated by tools/naturalize-dashboard.mjs from the gated source snapshot.",
	...stringFields.map(
		(name) =>
			`export const ${name} = ${JSON.stringify(naturalizeMarkup(readExportedValue(sourceData, name)))};`,
	),
	`export const dashboardPageRoot = ${JSON.stringify(pageRoot)} as const;`,
	"",
].join("\n");

await mkdir(path.dirname(naturalizedDataPath), { recursive: true });
await Promise.all([
	writeFile(
		path.join(vendorRoot, "naturalized.css"),
		naturalizeCss(sourceCss, path.join(vendorRoot, "source.css")),
	),
	writeFile(
		path.join(vendorRoot, "naturalized-composition.css"),
		naturalizeCss(compositionCss, path.join(vendorRoot, "composition.css")),
	),
	writeFile(naturalizedDataPath, naturalizedData),
	writeFile(
		naturalizedScriptPath,
		replaceTokens(sourceScript, renameMap.attributes),
	),
]);

console.log(
	JSON.stringify(
		{
			classesRenamed: Object.keys(renameMap.classes).length,
			attributesRenamed: Object.keys(renameMap.attributes).length,
		},
		null,
		2,
	),
);
