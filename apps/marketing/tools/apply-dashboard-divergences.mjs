import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const marketingRoot = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	"..",
);
const sourceDataPath = path.join(
	marketingRoot,
	"src/components/generated/dashboard-data.ts",
);
const outputDataPath = path.join(
	marketingRoot,
	"src/components/generated/dashboard-branded-data.ts",
);
const artifactRoot = path.resolve(
	marketingRoot,
	"../../.context/gates/dashboard/d001",
);
const sanctionedLabels = ["Ask Attio", "Workflows"];
const voidElements = new Set([
	"area",
	"base",
	"br",
	"col",
	"embed",
	"hr",
	"img",
	"input",
	"link",
	"meta",
	"param",
	"source",
	"track",
	"wbr",
]);

const readExportedValue = (source, name) => {
	const line = source
		.split("\n")
		.find((candidate) => candidate.startsWith(`export const ${name} = `));
	if (!line) throw new Error(`Could not read dashboard field: ${name}`);
	return JSON.parse(
		line
			.slice(`export const ${name} = `.length)
			.replace(/ as const;$/, "")
			.replace(/;$/, ""),
	);
};

const normalizedText = (markup) =>
	markup
		.replace(/<[^>]+>/g, "")
		.replaceAll("&amp;", "&")
		.replaceAll("&nbsp;", " ")
		.replace(/\s+/g, " ")
		.trim();

const elementRanges = (markup) => {
	const nodes = [];
	const stack = [];
	const tag = /<\/?([A-Za-z][\w:-]*)(?:\s[^<>]*?)?\/?\s*>/g;
	for (const match of markup.matchAll(tag)) {
		const raw = match[0];
		const name = match[1].toLowerCase();
		const closing = raw.startsWith("</");
		if (closing) {
			for (let index = stack.length - 1; index >= 0; index -= 1) {
				if (stack[index].name !== name) continue;
				const node = stack[index];
				stack.length = index;
				node.endStart = match.index;
				node.end = match.index + raw.length;
				nodes.push(node);
				break;
			}
			continue;
		}
		if (raw.endsWith("/>") || voidElements.has(name)) continue;
		stack.push({
			name,
			start: match.index,
			innerStart: match.index + raw.length,
		});
	}
	return nodes;
};

const removeSanctionedNodes = (markup, field) => {
	const nodes = elementRanges(markup);
	const removals = [];
	for (const label of sanctionedLabels) {
		const candidates = nodes
			.filter((node) => {
				if (!Number.isFinite(node.endStart)) return false;
				const inner = markup.slice(node.innerStart, node.endStart);
				return inner.includes("<svg") && normalizedText(inner) === label;
			})
			.toSorted(
				(left, right) =>
					left.end - left.start - (right.end - right.start),
			);
		const target = candidates[0];
		if (!target) {
			throw new Error(`Could not find the sanctioned ${label} node in ${field}`);
		}
		const html = markup.slice(target.start, target.end);
		removals.push({
			field,
			label,
			start: target.start,
			end: target.end,
			bytes: Buffer.byteLength(html),
			sha256: createHash("sha256").update(html).digest("hex"),
			html,
		});
	}
	let result = markup;
	for (const removal of removals.toSorted((left, right) => right.start - left.start)) {
		result = result.slice(0, removal.start) + result.slice(removal.end);
	}
	for (const label of sanctionedLabels) {
		if (result.includes(`>${label}<`)) {
			throw new Error(`${label} remains after the sanctioned transform in ${field}`);
		}
	}
	return { result, removals };
};

const sourceData = await readFile(sourceDataPath, "utf8");
const stringFields = [
	"dashboardHtml",
	"shellHtml",
	"dataPanelHtml",
	"reportingPanelHtml",
	"mobileDataHtml",
	"mobileReportingHtml",
];
const transformed = {};
const removals = [];
for (const field of stringFields) {
	const change = removeSanctionedNodes(readExportedValue(sourceData, field), field);
	transformed[field] = change.result;
	removals.push(...change.removals);
}
const pageRoot = readExportedValue(sourceData, "dashboardPageRoot");

await mkdir(artifactRoot, { recursive: true });
await Promise.all([
	writeFile(
		outputDataPath,
		[
			"// Generated by tools/apply-dashboard-divergences.mjs; only D-003 is applied.",
			...stringFields.map(
				(field) => `export const ${field} = ${JSON.stringify(transformed[field])};`,
			),
			`export const dashboardPageRoot = ${JSON.stringify(pageRoot)} as const;`,
			"",
		].join("\n"),
	),
	writeFile(
		path.join(artifactRoot, "codemod-report.json"),
		`${JSON.stringify(
			{
				gate: "D-003-dashboard-removals",
				generatedAt: new Date().toISOString(),
				passed:
					removals.length === stringFields.length * sanctionedLabels.length,
				whitelist: sanctionedLabels,
				transformation: "remove-smallest-exact-text-node-containing-svg",
				removals,
			},
			null,
			2,
		)}\n`,
	),
]);

