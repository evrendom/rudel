import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import selectorParser from "postcss-selector-parser";

const marketingRoot = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	"..",
);
const vendorRoot = path.join(
	marketingRoot,
	"src/styles/vendor/interfere/hero-title",
);
const sourceDataPath = path.join(
	marketingRoot,
	"src/components/generated/hero-title-source-data.ts",
);
const naturalizedDataPath = path.join(
	marketingRoot,
	"src/components/generated/hero-title-data.ts",
);
const renameMapPath = path.join(
	marketingRoot,
	"tools/rename-map/hero-title.json",
);
const scopeClass = "opaline-hero-title-scope";

const renameMap = JSON.parse(await readFile(renameMapPath, "utf8"));
const replaceTokens = (source, replacements) => {
	let result = source;
	for (const [from, to] of Object.entries(replacements).toSorted(
		([left], [right]) => right.length - left.length,
	)) {
		result = result.replaceAll(from, to);
	}
	return result;
};

const zeroSpecificityScope = () => {
	const scope = selectorParser.pseudo({ value: ":where" });
	scope.append(
		selectorParser.selector({
			nodes: [selectorParser.className({ value: scopeClass })],
		}),
	);
	return scope;
};

const transformSelector = selectorParser((selectors) => {
	selectors.each((selector) => {
		selector.walkClasses((node) => {
			const renamed = renameMap.classes[node.value];
			if (renamed) node.value = renamed;
		});
		selector.walkAttributes((node) => {
			const renamed = renameMap.attributes[node.attribute];
			if (renamed) node.attribute = renamed;
		});
		selector.walkPseudos((node) => {
			if (node.value === ":root" || node.value === ":host") {
				node.replaceWith(selectorParser.className({ value: scopeClass }));
			}
		});
		selector.walkTags((node) => {
			if (node.value === "html" || node.value === "body") {
				node.replaceWith(selectorParser.className({ value: scopeClass }));
			}
		});
		let containsScope = false;
		selector.walkClasses((node) => {
			if (node.value === scopeClass) containsScope = true;
		});
		if (!containsScope) {
			selector.prepend(selectorParser.combinator({ value: " " }));
			selector.prepend(zeroSpecificityScope());
		}
	});
});

const naturalizeCss = (source, from) => {
	const root = postcss.parse(source, { from });
	root.walkRules((rule) => {
		if (
			rule.parent?.type === "atrule" &&
			rule.parent.name.endsWith("keyframes")
		) {
			return;
		}
		rule.selector = transformSelector.processSync(rule.selector);
	});
	return root.toString();
};

const readExportedString = (source, name) => {
	const match = source.match(new RegExp(`export const ${name} = (.*);`));
	if (!match?.[1]) throw new Error(`Could not read hero title field: ${name}`);
	return JSON.parse(match[1]);
};

const [sourceCss, isolationCss, sourceData] = await Promise.all([
	readFile(path.join(vendorRoot, "source.css"), "utf8"),
	readFile(path.join(vendorRoot, "isolation.css"), "utf8"),
	readFile(sourceDataPath, "utf8"),
]);
const naturalizedHtml = replaceTokens(
	readExportedString(sourceData, "titleHtml"),
	{
		...renameMap.classes,
		...renameMap.attributes,
	},
);

await mkdir(path.dirname(naturalizedDataPath), { recursive: true });
await Promise.all([
	writeFile(
		path.join(vendorRoot, "naturalized.css"),
		naturalizeCss(sourceCss, path.join(vendorRoot, "source.css")),
	),
	writeFile(
		path.join(vendorRoot, "naturalized-isolation.css"),
		naturalizeCss(isolationCss, path.join(vendorRoot, "isolation.css")),
	),
	writeFile(
		naturalizedDataPath,
		`// Generated by tools/naturalize-hero-title.mjs from the gated source snapshot.\nexport const titleHtml = ${JSON.stringify(naturalizedHtml)};\n`,
	),
]);

console.log(
	JSON.stringify(
		{
			classesRenamed: Object.keys(renameMap.classes).length,
			attributesRenamed: Object.keys(renameMap.attributes).length,
		},
		null,
		2,
	),
);
